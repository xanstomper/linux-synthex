#!/usr/bin/env bash
# Solus Boot Optimizer — disables slow units, sets fast kernel cmdline,
# enables zstd hostonly initramfs + fail-fast init. Safe to re-run.

set -euo pipefail

AMBER='\033[38;5;214m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0m'

ok()   { echo -e "  ${GREEN}✅${NC} $*"; }
skip() { echo -e "  ${YELLOW}•${NC} $*"; }
die()  { echo -e "  ${RED}✗${NC} $*"; }

if [ "$(id -u)" -ne 0 ]; then
    die "must run as root"
    exit 1
fi

echo -e "${AMBER}══════════════════════════════════════════════${NC}"
echo -e "${AMBER}  ⚡ Solus Boot Optimizer${NC}"
echo -e "${AMBER}══════════════════════════════════════════════${NC}"
echo ""

# ─── 1. Disable slow / unused boot units ───────────────────────
echo "Disabling slow boot units..."
SLOW_UNITS=(
    ModemManager.service
    abrtd.service abrt-journal-core.service abrt-oops.service abrt-vmcore.service
    kdump.service
)
for u in "${SLOW_UNITS[@]}"; do
    if systemctl list-unit-files "$u" &>/dev/null; then
        systemctl disable "$u" 2>/dev/null || true
        ok "disabled $u"
    else
        skip "$u not installed"
    fi
done

# Mask the wait-online blockers outright (biggest single boot win)
for u in NetworkManager-wait-online.service systemd-networkd-wait-online.service; do
    if systemctl list-unit-files "$u" &>/dev/null; then
        systemctl mask "$u" 2>/dev/null || true
        ok "masked $u"
    fi
done
echo ""

# ─── 2. Fast kernel command line ───────────────────────────────
echo "Setting fast kernel command line..."
FAST_TOKENS=(
    quiet rw nowatchdog
    nvme_core.default_ps_max_latency_us=0
    amd-pstate=active intel_pstate=active
    cpufreq.default_governor=schedutil
    processor.max_freq=0
)
GRUB_CFG="/etc/default/grub"
if [ -f "$GRUB_CFG" ]; then
    if grep -q '^GRUB_CMDLINE_LINUX_DEFAULT=' "$GRUB_CFG"; then
        CUR=$(grep '^GRUB_CMDLINE_LINUX_DEFAULT=' "$GRUB_CFG" | cut -d'"' -f2)
        NEW="$CUR"
        for tok in "${FAST_TOKENS[@]}"; do
            case "$NEW" in
                *"$tok"*) ;;
                *) NEW="$NEW $tok" ;;
            esac
        done
        NEW=$(echo "$NEW" | sed -e 's/\brhgb\b//g' -e 's/  */ /g' -e 's/^ //; s/ $//')
        sed -i "s|^GRUB_CMDLINE_LINUX_DEFAULT=.*|GRUB_CMDLINE_LINUX_DEFAULT=\"$NEW\"|" "$GRUB_CFG"
        ok "updated GRUB_CMDLINE_LINUX_DEFAULT"
    else
        echo "GRUB_CMDLINE_LINUX_DEFAULT=\"${FAST_TOKENS[*]}\"" >> "$GRUB_CFG"
        ok "added GRUB_CMDLINE_LINUX_DEFAULT"
    fi

    grep -q '^GRUB_TIMEOUT=' "$GRUB_CFG" && \
        sed -i 's/^GRUB_TIMEOUT=.*/GRUB_TIMEOUT=2/' "$GRUB_CFG" && ok "GRUB_TIMEOUT=2"
    grep -q '^GRUB_DISABLE_SUBMENU=' "$GRUB_CFG" && \
        sed -i 's/^GRUB_DISABLE_SUBMENU=.*/GRUB_DISABLE_SUBMENU=y/' "$GRUB_CFG" && ok "GRUB_DISABLE_SUBMENU=y"

    if command -v grub2-mkconfig &>/dev/null; then
        grub2-mkconfig -o /boot/grub2/grub.cfg 2>/dev/null || \
        grub2-mkconfig -o /boot/efi/EFI/solus/grub.cfg 2>/dev/null || true
        ok "regenerated GRUB config"
    fi
else
    skip "$GRUB_CFG not found (systemd-boot: edit /boot/loader/entries/*.conf)"
fi
echo ""

# ─── 3. Fast initramfs (zstd, hostonly, omit unused) ───────────
echo "Configuring fast initramfs..."
DRACUT_DROP="/etc/dracut.conf.d/solus-fast.conf"
cat > "$DRACUT_DROP" <<'EOF'
# Solus fast-initramfs drop-in (generated by solus boot-optimize.sh)
hostonly="yes"
hostonly_cmdline="yes"
compress="zstd"
compress_args="-1"
early_microcode="yes"
omit_drivers+=" floppy firewire-core firewire-sbp2 firewire-ohci sbp2 "
omit_drivers+=" pcnet32 3c59x dl2k netconsole "
omit_drivers+=" aic7xxx aic79xx "
add_drivers+=" nvme ahci xhci-pci btrfs ext4 vfat "
EOF
ok "wrote $DRACUT_DROP"

if command -v dracut &>/dev/null; then
    KVER=$(uname -r)
    if dracut --force --kver "$KVER" 2>/dev/null; then
        ok "regenerated initramfs for $KVER"
    else
        skip "initramfs regen deferred (rerun after kernel update)"
    fi
fi
echo ""

# ─── 4. Parallel / fail-fast init ──────────────────────────────
echo "Tuning systemd init..."
SYS_CONF="/etc/systemd/system.conf"
mkdir -p /etc/systemd
touch "$SYS_CONF"
set_conf() {
    local key="$1" val="$2"
    if grep -q "^${key}=" "$SYS_CONF"; then
        sed -i "s|^${key}=.*|${key}=${val}|" "$SYS_CONF"
    else
        echo "${key}=${val}" >> "$SYS_CONF"
    fi
}
set_conf DefaultTimeoutStartSec 15s
set_conf DefaultDeviceTimeoutSec 15s
ok "systemd fail-fast timeouts set"
echo ""

# ─── 5. Enable boot profiling ──────────────────────────────────
if systemctl list-unit-files solus-boot-profile.service &>/dev/null; then
    systemctl enable solus-boot-profile.service 2>/dev/null && ok "enabled boot profiling"
fi

echo ""
echo -e "${AMBER}══════════════════════════════════════════════${NC}"
echo -e "  ${GREEN}✅ Boot optimization applied${NC}"
echo -e "  Reboot to measure: ${YELLOW}systemd-analyze${NC}"
echo -e "${AMBER}══════════════════════════════════════════════${NC}"
