#!/usr/bin/env bash
# ============================================================
# SynthOS — GPU Driver Manager
# /usr/sbin/gpu-driver-manager
#
# Detects GPU hardware, installs appropriate drivers, applies
# configuration, and manages driver switching (open vs proprietary).
#
# Part of synthex-gpu-drivers package
# ============================================================

set -euo pipefail

# --- Configuration ---
CONFIG_DIR="/etc/default"
AMD_CONFIG="${CONFIG_DIR}/amdgpu"
NVIDIA_CONFIG="${CONFIG_DIR}/nvidia"
INTEL_CONFIG="${CONFIG_DIR}/intel-gpu"
MODPROBE_DIR="/etc/modprobe.d"
INITRAMFS_DIR="/etc/initramfs-tools"
DRACUT_CONF_DIR="/etc/dracut.conf.d"

# --- Color output ---
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

info()    { echo -e "${GREEN}[INFO]${NC}  $*"; }
warn()    { echo -e "${YELLOW}[WARN]${NC}  $*"; }
error()   { echo -e "${RED}[ERROR]${NC} $*"; }
header()  { echo -e "\n${BLUE}═══ $* ═══${NC}\n"; }

# ============================================================
# HARDWARE DETECTION
# ============================================================

detect_gpu_vendor() {
    # Returns: amd, nvidia, intel, or unknown
    local vendors=()
    
    # Check via lspci
    if command -v lspci &>/dev/null; then
        while read -r line; do
            case "$line" in
                *"AMD"*|*"ATI"*|*"Radeon"*)
                    vendors+=("amd")
                    ;;
                *"NVIDIA"*|*"GeForce"*|*"Quadro"*|*"Tegra"*)
                    vendors+=("nvidia")
                    ;;
                *"Intel"*|*"Arc"*|*"Iris"*|*"HD Graphics"*|*"UHD Graphics"*)
                    vendors+=("intel")
                    ;;
            esac
        done < <(lspci -nn 2>/dev/null | grep -iE "(vga|3d|display)")
    fi
    
    # Fallback: check /sys/class/drm
    if [[ ${#vendors[@]} -eq 0 ]]; then
        for dev in /sys/class/drm/card*/device/vendor; do
            [[ -f "$dev" ]] || continue
            local vendor_id
            vendor_id=$(cat "$dev" 2>/dev/null)
            case "$vendor_id" in
                "0x1002") vendors+=("amd") ;;
                "0x10de") vendors+=("nvidia") ;;
                "0x8086") vendors+=("intel") ;;
            esac
        done
    fi
    
    # Deduplicate and output
    [[ ${#vendors[@]} -eq 0 ]] && { echo "unknown"; return; }
    printf '%s\n' "${vendors[@]}" | sort -u | tr '\n' ' '
}

detect_nvidia_driver_type() {
    # Check if proprietary nvidia.ko is loaded
    if lsmod | grep -q "^nvidia "; then
        echo "proprietary"
        return
    fi
    # Check if nouveau is loaded
    if lsmod | grep -q "^nouveau "; then
        echo "nouveau"
        return
    fi
    # Neither loaded — check what's available
    if modinfo nvidia &>/dev/null 2>&1; then
        echo "proprietary-available"
        return
    fi
    if modinfo nouveau &>/dev/null 2>&1; then
        echo "nouveau-available"
        return
    fi
    echo "none"
}

detect_amd_gpu_family() {
    # Detect AMD GPU architecture for specific tuning
    if ! command -v lspci &>/dev/null; then
        echo "unknown"; return
    fi
    
    local gpu_info
    gpu_info=$(lspci -nn 2>/dev/null | grep -iE "(amd|ati|radeon)" | grep -iE "(vga|3d|display)" | head -1)
    
    case "$gpu_info" in
        *"RDNA"*|*"RX 7"*|*"RX 9"*)  echo "rdna3" ;;
        *"RX 6"*|*"RX 5"*)            echo "rdna2" ;;
        *"RX 4"*|*"Vega"*|*"VII"*)    echo "rdna1" ;;
        *"RX 3"*|*"R9"*)              echo "gcn4" ;;
        *"R7"*|*"HD 7"*|*"HD 8"*)     echo "gcn1" ;;
        *)                             echo "unknown" ;;
    esac
}

# ============================================================
# CONFIGURATION GENERATION
# ============================================================

generate_amd_config() {
    info "Generating AMD GPU configuration..."
    
    # Source default config if exists
    [[ -f "$AMD_CONFIG" ]] && source "$AMD_CONFIG"
    
    # Write modprobe config
    cat > "${MODPROBE_DIR}/amdgpu.conf" << 'MODAMD'
# AMD GPU module options — auto-generated by gpu-driver-manager
options amdgpu si_support=1 cik_support=1
options amdgpu dc=1
options amdgpu ppfeaturemask=0xffffffff
MODAMD
    
    # Write udev rule for AMD GPU permissions
    cat > /etc/udev/rules.d/60-amdgpu.rules << 'UDEVAMD'
# AMD GPU permissions for gaming
KERNEL=="card*", SUBSYSTEM=="drm", DRIVERS=="amdgpu", GROUP="games", MODE="0660"
KERNEL=="renderD*", SUBSYSTEM=="drm", DRIVERS=="amdgpu", GROUP="games", MODE="0660"
UDEVAMD
    
    info "AMD configuration generated."
}

generate_nvidia_config() {
    local driver_type="$1"
    
    if [[ "$driver_type" == "proprietary" ]] || [[ "$driver_type" == "proprietary-available" ]]; then
        info "Generating NVIDIA proprietary driver configuration..."
        
        cat > "${MODPROBE_DIR}/nvidia.conf" << 'MODNV'
# NVIDIA kernel module options — auto-generated by gpu-driver-manager
options nvidia-drm modeset=1 fbdev=1
options nvidia NVreg_EnableGpuFirmware=0
options nvidia NVreg_RegistryDwords=RMIntrLock=0x01
options nvidia NVreg_UsePageAttributeTable=1
options nvidia NVreg_InitializeSystemMemoryWithZeroes=0
MODNV
        
        # Blacklist nouveau
        cat > "${MODPROBE_DIR}/nvidia-blacklist-nouveau.conf" << 'BLNV'
# Blacklist Nouveau driver when using NVIDIA proprietary
blacklist nouveau
options nouveau modeset=0
BLNV
        
        # Ensure initramfs includes NVIDIA modules
        if command -v dracut &>/dev/null; then
            echo 'add_drivers+=" nvidia nvidia-drm nvidia-modeset nvidia-uvm "' \
                > "${DRACUT_CONF_DIR}/nvidia-drivers.conf"
        fi
        
        info "NVIDIA proprietary configuration generated."
        
    elif [[ "$driver_type" == "nouveau" ]] || [[ "$driver_type" == "nouveau-available" ]]; then
        info "Generating Nouveau (open-source) driver configuration..."
        
        cat > "${MODPROBE_DIR}/nouveau.conf" << 'MODNVN'
# Nouveau kernel module options — auto-generated by gpu-driver-manager
options nouveau runpm=0
options nouveau modeset=1
MODNVN
        
        # Remove nouveau blacklist if present
        rm -f "${MODPROBE_DIR}/nvidia-blacklist-nouveau.conf"
        
        info "Nouveau configuration generated."
    fi
    
    # Common udev rules for NVIDIA
    cat > /etc/udev/rules.d/60-nvidia.rules << 'UDEVNV'
# NVIDIA GPU permissions for gaming
KERNEL=="card*", SUBSYSTEM=="drm", DRIVERS=="nvidia", GROUP="games", MODE="0660"
KERNEL=="nvidia*", SUBSYSTEM=="nvidia", GROUP="games", MODE="0660"
KERNEL=="nvidia-uvm*", SUBSYSTEM=="nvidia-uvm", GROUP="games", MODE="0660"
UDEVNV
}

generate_intel_config() {
    info "Generating Intel GPU configuration..."
    
    cat > "${MODPROBE_DIR}/i915.conf" << 'MODINT'
# Intel i915 module options — auto-generated by gpu-driver-manager
options i915 enable_psr=0
options i915 enable_fbc=1
options i915 fastboot=1
options i915 enable_guc=3
options i915 enable_dpcd_backlight=1
MODINT
    
    cat > /etc/udev/rules.d/60-intel-gpu.rules << 'UDEVINT'
# Intel GPU permissions for gaming
KERNEL=="card*", SUBSYSTEM=="drm", DRIVERS=="i915", GROUP="games", MODE="0660"
KERNEL=="renderD*", SUBSYSTEM=="drm", DRIVERS=="i915", GROUP="games", MODE="0660"
UDEVINT
    
    info "Intel configuration generated."
}

# ============================================================
# DRIVER INSTALLATION
# ============================================================

install_amd_drivers() {
    header "Installing AMD GPU Drivers"
    
    # Packages needed for AMD
    local pkg_list=(
        mesa mesa-va-drivers mesa-vdpau-drivers
        libva libva-utils
        vulkan-loader vulkan-tools
        mesa-vulkan-drivers mesa-dri-drivers
        linux-firmware-amd
        amdgpu-core
    )
    
    if command -v eopkg &>/dev/null; then
        info "Installing AMD packages via eopkg..."
        eopkg install "${pkg_list[@]}"
    elif command -v dnf &>/dev/null; then
        info "Installing AMD packages via dnf..."
        dnf install -y "${pkg_list[@]}"
    else
        warn "No known package manager found. Please install AMD drivers manually."
        warn "Required packages: ${pkg_list[*]}"
    fi
    
    generate_amd_config
}

install_nvidia_drivers() {
    local driver_type="${1:-proprietary}"
    
    if [[ "$driver_type" == "proprietary" ]]; then
        header "Installing NVIDIA Proprietary Drivers"
        
        local pkg_list=(
            nvidia-driver nvidia-driver-dkms
            nvidia-settings nvidia-utils
            nvidia-compute-utils
            vulkan-loader vulkan-tools
        )
        
        if command -v eopkg &>/dev/null; then
            eopkg install "${pkg_list[@]}"
        elif command -v dnf &>/dev/null; then
            dnf install -y "${pkg_list[@]}"
        else
            warn "No known package manager found."
        fi
        
        generate_nvidia_config "proprietary"
        
    elif [[ "$driver_type" == "nouveau" ]]; then
        header "Installing Nouveau Open-Source Drivers"
        
        local pkg_list=(
            mesa mesa-dri-drivers
            mesa-vulkan-drivers mesa-nouveau-drivers
            libva libva-utils
            vulkan-loader vulkan-tools
            linux-firmware-nvidia
        )
        
        if command -v eopkg &>/dev/null; then
            eopkg install "${pkg_list[@]}"
        elif command -v dnf &>/dev/null; then
            dnf install -y "${pkg_list[@]}"
        else
            warn "No known package manager found."
        fi
        
        generate_nvidia_config "nouveau"
    fi
}

install_intel_drivers() {
    header "Installing Intel GPU Drivers"
    
    local pkg_list=(
        mesa mesa-dri-drivers
        mesa-vulkan-drivers mesa-intel-drivers
        intel-media-driver intel-vaapi-driver
        libva libva-utils
        vulkan-loader vulkan-tools
        intel-compute-runtime
        linux-firmware-intel
        intel-gpu-tools
    )
    
    if command -v eopkg &>/dev/null; then
        eopkg install "${pkg_list[@]}"
    elif command -v dnf &>/dev/null; then
        dnf install -y "${pkg_list[@]}"
    else
        warn "No known package manager found."
    fi
    
    generate_intel_config
}

# ============================================================
# DRIVER SWITCHING (NVIDIA Open ↔ Proprietary)
# ============================================================

switch_nvidia_driver() {
    local target="${1}"  # "proprietary" or "nouveau"
    
    if [[ ! -d "$MODPROBE_DIR" ]]; then
        error "Modprobe directory not found!"
        exit 1
    fi
    
    info "Switching NVIDIA driver to: ${target}"
    
    # Disable current driver
    if lsmod | grep -q "^nvidia "; then
        info "Unloading NVIDIA proprietary modules..."
        rmmod nvidia-drm nvidia-modeset nvidia-uvm nvidia 2>/dev/null || true
    fi
    if lsmod | grep -q "^nouveau "; then
        info "Unloading Nouveau modules..."
        rmmod nouveau 2>/dev/null || true
    fi
    
    # Generate new config
    generate_nvidia_config "$target"
    
    # Rebuild initramfs
    if command -v dracut &>/dev/null; then
        info "Rebuilding initramfs with dracut..."
        dracut --force
    elif command -v update-initramfs &>/dev/null; then
        info "Rebuilding initramfs..."
        update-initramfs -u
    fi
    
    info "NVIDIA driver switch complete. A reboot is required."
    info "Run: sudo reboot"
}

# ============================================================
# STATUS REPORTING
# ============================================================

show_status() {
    header "GPU Driver Status"
    
    local vendors
    vendors=$(detect_gpu_vendor)
    
    echo "Detected GPU vendors: ${vendors}"
    echo ""
    
    for vendor in $vendors; do
        case "$vendor" in
            amd)
                echo "── AMD GPU ──"
                echo "  Family:      $(detect_amd_gpu_family)"
                echo "  Kernel mod:  $(lsmod | grep -q "^amdgpu " && echo 'Loaded ✓' || echo 'Not loaded')"
                echo "  Mesa:        $(glxinfo -B 2>/dev/null | grep "OpenGL renderer" | head -1 || echo 'N/A')"
                echo "  Vulkan:      $(vulkaninfo 2>/dev/null | grep "deviceName" | head -1 || echo 'N/A')"
                echo "  Driver cfg:  $([[ -f "$AMD_CONFIG" ]] && echo 'Present ✓' || echo 'Missing')"
                ;;
            nvidia)
                echo "── NVIDIA GPU ──"
                local nv_type
                nv_type=$(detect_nvidia_driver_type)
                echo "  Driver type: ${nv_type}"
                if [[ "$nv_type" == "proprietary" ]]; then
                    echo "  Driver ver:  $(cat /proc/driver/nvidia/version 2>/dev/null | head -1 || echo 'N/A')"
                    echo "  VRAM:        $(nvidia-smi --query-gpu=memory.total --format=csv,noheader,nounits 2>/dev/null || echo 'N/A') MB"
                fi
                echo "  Kernel mod:  $(lsmod | grep -qE "^(nvidia|nouveau) " && echo 'Loaded ✓' || echo 'Not loaded')"
                echo "  Driver cfg:  $([[ -f "$NVIDIA_CONFIG" ]] && echo 'Present ✓' || echo 'Missing')"
                ;;
            intel)
                echo "── Intel GPU ──"
                echo "  Kernel mod:  $(lsmod | grep -q "^i915 " && echo 'Loaded ✓' || echo 'Not loaded')"
                echo "  Mesa:        $(glxinfo -B 2>/dev/null | grep "OpenGL renderer" | head -1 || echo 'N/A')"
                echo "  Vulkan:      $(vulkaninfo 2>/dev/null | grep "deviceName" | head -1 || echo 'N/A')"
                echo "  Driver cfg:  $([[ -f "$INTEL_CONFIG" ]] && echo 'Present ✓' || echo 'Missing')"
                ;;
        esac
        echo ""
    done
    
    echo "── Gaming Performance Status ──"
    echo "  Gamemode:   $(pidof gamemoded >/dev/null && echo 'Running ✓' || echo 'Not running')"
    echo "  Gamescope:  $(command -v gamescope && echo 'Available ✓' || echo 'Not installed')"
    echo "  MangoHUD:   $(command -v mangohud && echo 'Available ✓' || echo 'Not installed')"
}

# ============================================================
# AUTO-DETECT AND INSTALL
# ============================================================

auto_install() {
    header "Auto-detecting and installing GPU drivers"
    
    local vendors
    vendors=$(detect_gpu_vendor)
    
    if [[ "$vendors" == "unknown" ]]; then
        error "No GPU detected. Cannot install drivers."
        exit 1
    fi
    
    info "Detected GPU vendor(s): ${vendors}"
    
    for vendor in $vendors; do
        case "$vendor" in
            amd)     install_amd_drivers ;;
            nvidia)  
                local nv_type
                nv_type=$(detect_nvidia_driver_type)
                # Read config preference
                local prefer="proprietary"
                [[ -f "$NVIDIA_CONFIG" ]] && source "$NVIDIA_CONFIG"
                case "${AUTO_PREFER:-proprietary}" in
                    proprietary) install_nvidia_drivers "proprietary" ;;
                    nouveau)     install_nvidia_drivers "nouveau" ;;
                esac
                ;;
            intel)   install_intel_drivers ;;
        esac
    done
    
    header "Installation Complete"
    info "Please reboot for changes to take effect."
}

# ============================================================
# MAIN
# ============================================================

usage() {
    cat << EOF
Synthex GPU Driver Manager — Detect, install, and switch GPU drivers

USAGE:
  gpu-driver-manager [command]

COMMANDS:
  status          Show current GPU driver status
  auto-install    Auto-detect GPUs and install appropriate drivers
  install-amd     Install AMD GPU drivers
  install-nvidia  Install NVIDIA proprietary drivers
  install-nouveau Install Nouveau (open-source NVIDIA) drivers
  install-intel   Install Intel GPU drivers
  switch-nvidia   Switch between NVIDIA proprietary and Nouveau drivers
                  Usage: switch-nvidia (proprietary|nouveau)
  help            Show this help message

EXAMPLES:
  gpu-driver-manager status
  gpu-driver-manager auto-install
  gpu-driver-manager switch-nvidia proprietary

EOF
}

main() {
    # Require root for install/switch operations
    local cmd="${1:-status}"
    
    case "$cmd" in
        status)
            show_status
            ;;
        auto-install|auto_install)
            [[ $EUID -eq 0 ]] || { error "Must be root to install drivers."; exit 1; }
            auto_install
            ;;
        install-amd|install_amd)
            [[ $EUID -eq 0 ]] || { error "Must be root."; exit 1; }
            install_amd_drivers
            ;;
        install-nvidia|install_nvidia)
            [[ $EUID -eq 0 ]] || { error "Must be root."; exit 1; }
            install_nvidia_drivers "proprietary"
            ;;
        install-nouveau|install_nouveau)
            [[ $EUID -eq 0 ]] || { error "Must be root."; exit 1; }
            install_nvidia_drivers "nouveau"
            ;;
        install-intel|install_intel)
            [[ $EUID -eq 0 ]] || { error "Must be root."; exit 1; }
            install_intel_drivers
            ;;
        switch-nvidia|switch_nvidia)
            [[ $EUID -eq 0 ]] || { error "Must be root."; exit 1; }
            local target="${2:-}"
            [[ -z "$target" ]] && { error "Usage: $0 switch-nvidia (proprietary|nouveau)"; exit 1; }
            [[ "$target" =~ ^(proprietary|nouveau)$ ]] || { error "Target must be 'proprietary' or 'nouveau'"; exit 1; }
            switch_nvidia_driver "$target"
            ;;
        help|--help|-h)
            usage
            ;;
        *)
            error "Unknown command: $cmd"
            usage
            exit 1
            ;;
    esac
}

main "$@"
